-- Run in Supabase SQL Editor. Review policies before production use.
create table if not exists public.group_messages (
  id bigint generated by default as identity primary key,
  group_id text not null,
  user_id text not null,
  display_name text not null,
  content text not null check (char_length(content) between 1 and 5000),
  created_at timestamptz not null default now()
);
create index if not exists group_messages_group_created_idx on public.group_messages(group_id, created_at);
alter table public.group_messages enable row level security;
-- Starter policies permit authenticated app users to read/insert. Tighten with verified JWT claims before public launch.
create policy "authenticated users can read group messages" on public.group_messages
  for select to authenticated using (true);
create policy "authenticated users can send group messages" on public.group_messages
  for insert to authenticated with check (true);

